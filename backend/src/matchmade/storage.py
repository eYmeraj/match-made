"""On-disk layout for datasets and jobs under the data directory.

data/
  datasets/<id>/source.<ext>   original upload
  datasets/<id>/data.parquet   all-string table
  datasets/<id>/meta.json      DatasetMeta
  jobs/<id>/config.json        MatchConfig
  jobs/<id>/candidates.parquet scored pairs kept for the results page
  jobs/<id>/summary.json       JobSummary, written when the job succeeds
"""

from __future__ import annotations

import os
import shutil
import uuid
from datetime import UTC, datetime
from pathlib import Path

import polars as pl
from pydantic import BaseModel, Field

from matchmade.profiling import ColumnProfile, profile_frame
from matchmade.readers import ParseInfo, ParseOptions, read_file
from matchmade.schemas import MatchConfig


class NotFoundError(LookupError):
    pass


class DatasetMeta(BaseModel):
    id: str
    filename: str
    rows: int
    columns: list[ColumnProfile]
    parse: ParseInfo
    created_at: datetime


def new_id() -> str:
    return uuid.uuid4().hex


def _check_id(value: str) -> str:
    # Ids are generated by us; anything else is a lookup miss (and never a path).
    if len(value) != 32 or not all(c in "0123456789abcdef" for c in value):
        raise NotFoundError(value)
    return value


def write_atomic(path: Path, text: str) -> None:
    tmp = path.with_suffix(path.suffix + ".tmp")
    tmp.write_text(text)
    os.replace(tmp, path)


class Storage:
    def __init__(self, root: Path) -> None:
        self.root = root
        (root / "datasets").mkdir(parents=True, exist_ok=True)
        (root / "jobs").mkdir(parents=True, exist_ok=True)

    # --- datasets -------------------------------------------------------------------

    def dataset_dir(self, dataset_id: str) -> Path:
        path = self.root / "datasets" / _check_id(dataset_id)
        if not path.is_dir():
            raise NotFoundError(dataset_id)
        return path

    def new_dataset_dir(self) -> tuple[str, Path]:
        dataset_id = new_id()
        path = self.root / "datasets" / dataset_id
        path.mkdir()
        return dataset_id, path

    def source_path(self, dataset_id: str) -> Path:
        return next(self.dataset_dir(dataset_id).glob("source.*"))

    def parse_dataset(self, dataset_id: str, filename: str, options: ParseOptions) -> DatasetMeta:
        directory = self.dataset_dir(dataset_id)
        frame, info = read_file(self.source_path(dataset_id), filename, options)
        frame.write_parquet(directory / "data.parquet")
        meta = DatasetMeta(
            id=dataset_id,
            filename=filename,
            rows=frame.height,
            columns=profile_frame(frame),
            parse=info,
            created_at=datetime.now(UTC),
        )
        write_atomic(directory / "meta.json", meta.model_dump_json())
        return meta

    def dataset_meta(self, dataset_id: str) -> DatasetMeta:
        path = self.dataset_dir(dataset_id) / "meta.json"
        if not path.exists():
            raise NotFoundError(dataset_id)
        return DatasetMeta.model_validate_json(path.read_text())

    def read_dataset(self, dataset_id: str, columns: list[str] | None = None) -> pl.DataFrame:
        return pl.read_parquet(self.dataset_dir(dataset_id) / "data.parquet", columns=columns)

    def delete_dataset(self, dataset_id: str) -> None:
        shutil.rmtree(self.dataset_dir(dataset_id))

    # --- jobs -----------------------------------------------------------------------

    def job_dir(self, job_id: str) -> Path:
        path = self.root / "jobs" / _check_id(job_id)
        if not path.is_dir():
            raise NotFoundError(job_id)
        return path

    def create_job(self, config: MatchConfig) -> str:
        job_id = new_id()
        path = self.root / "jobs" / job_id
        path.mkdir()
        write_atomic(path / "config.json", config.model_dump_json())
        return job_id

    def job_config(self, job_id: str) -> MatchConfig:
        return MatchConfig.model_validate_json((self.job_dir(job_id) / "config.json").read_text())


class JobSummary(BaseModel):
    rows_a: int
    rows_b: int
    candidate_pairs: int
    kept_pairs: int
    keep_from: float
    rule_stats: list[dict[str, int]] = Field(default_factory=list)
    seconds: dict[str, float] = Field(default_factory=dict)
